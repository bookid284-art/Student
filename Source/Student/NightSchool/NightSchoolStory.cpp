	const TCHAR* EndingTitle(ENightEnding Ending, bool bFromFear)
	{
		switch (Ending)
		{
		case ENightEnding::Publication: return TEXT("出版");
		case ENightEnding::BurnRegister: return TEXT("焚册");
		case ENightEnding::Stay: return TEXT("留下");
		case ENightEnding::Reply: return TEXT("回信");
		case ENightEnding::HalfPage: return TEXT("半页");
		case ENightEnding::Nameless: return bFromFear ? TEXT("无名 · 涂掉") : TEXT("无名 · 空白");
		default: return TEXT("回课");
		}
	}

	const TCHAR* EndingBody(ENightEnding Ending, bool bFromFear)
	{
		switch (Ending)
		{
		case ENightEnding::Publication:
			return TEXT("你在后园的石桌上摊开论文。天还没亮，拆迁队的灯已经排到了江堤上。你把林秋禾写成了“女鬼”，把赵铁生写成了“敲门声”，把周棉写成了“不可靠的童年叙述”。编辑部凌晨回了消息：标题改成《被抹去的夜校：一座楼的灵魂》，阅读量会很好。\n\n你盯着“灵魂”两个字，删掉，又补了回去。没有这两个字，林秋禾就只是一个没能把“林秀兰”教完的十九岁姑娘。这样的故事不吓人，也不容易被转发。\n\n一周后，拆楼暂停。人们来楼前拍照，问哪里闹鬼。没有人问林秀兰后来有没有学会自己的名字。评论区有一条没有头像的留言：“不要把我姑姑写成鬼。她只是想让我外婆自己签字。”你把那条评论设成了精选。因为精选比删除更像纪念。\n\n天亮的时候你走出楼。手机还在震。你忽然发现自己不会念“秀”字了。不是忘记，是嘴里那个字自动变成了“鬼”。你合上嘴，像合上一本已经出版的书。\n\n纪念如果必须把人变成传说，那传说就是第二座锅炉。");
		case ENightEnding::BurnRegister:
			return TEXT("你把名册、红烛和自己的论文提纲一起塞进火盆。火很老实，先吃纸，再吃你给这些纸起的标题。灰是白的，不像传说里那样是黑的。\n\n早上周望年站在警戒线外。他看着你空空的手，问：“写不了了？”你说：“没有这所夜校。”他点头，哭得很小，像怕被人看见还欠着什么。“谢谢你，”他说，又立刻改口，“对不起。”\n\n楼按时倒下。尘土盖过江面。一个路过的小孩问他妈妈这原来是什么。妈妈说：“旧的。”小孩又问旧的是什么。妈妈拉他过马路。\n\n你后来在人才市场填表，在“精通技能”一栏写下“文献综述”。字很工整。你没有再写错任何名字，因为你决定少写一些名字。\n\n火还在烧的时候，你听见很轻的一声，像拇指按在印泥上。火里没有手。声音停了。从此再也没有人把那一声听完。\n\n沉默保护了活人，也替死者把最后一课烧完了。");
		case ENightEnding::Stay:
			return TEXT("你在讲台前坐下。名册摊开，三个名字都在。你的名字写在黑板右下角，笔画是对的。红领巾叠好，放在第一排的桌角，糖纸还在。你没有把它交给期刊，也没有把它交给火。\n\n窗外的天色停在除夕前的那一分钟。拆迁队的灯远得像另一条河。林秋禾坐在第一排，裙子上的水迹不再扩大。她看着你，问最后一个字怎么写。不是“鬼”。是“恕”。\n\n你在黑板上写下“恕”。她摇头，说：“不是他们恕我。是我娘以后签字的时候，手不要发抖。”你把字擦了，改写成“林秀兰”。她跟着你的笔在空气里画。画到“兰”的最后一笔，楼道里的钟走了一下，又停了。\n\n你的手机在讲台抽屉里响。号码是你的。你不接。很多年以后，一个新的学生推开这扇已经不存在的门，对空气里的你说导师不让写夜校。你把粉笔递出去，没有告诉他你的名字。你怕自己的名字一旦被念对，天就会亮，而这节课还差一个人学会签字。\n\n救赎如果必须有人留下来，留下来的那个还算不算走完了自己的一生。");
		case ENightEnding::Reply:
			return TEXT("你没有发表，也没有烧。你把名册、林秋禾没写完的字和周望年那页批注订在一起，放进后园生锈的信箱。你只加了一句：字是她的，不是我的，也不是您的。\n\n信箱没有邮戳。第二天周望年还是收到了。有些信不经过邮局，经过一个人突然旧病复发的记忆。他从学院退休提前了三年。没有发布会。社区活动室的灯管坏了一根，他自费换上，每周二晚上教人写自己的名字。学员不多。有个老阿姨写了四个月，终于在拆迁补偿协议上签下“林秀兰”。她签字的时候没有人鼓掌。空调很响。\n\n旧楼还是拆了。没有鬼走出来，因为没有人再需要鬼来替一个名字找位置。你的论文成了空白文档，空白得像一条还没被写上字的河。你坐在活动室最后一排，没有自我介绍。周望年点名时顿了顿，跳过了你。他看见你了。他只是终于学会，有些名字不必再由他来说一遍。\n\n下课，林秀兰把笔帽扣好，放进布袋。她问旁边的人下一课学什么。那个人说：“学写你女儿的名字。”她笑了一下，说：“她叫秋禾。秋是秋天的秋，禾是还没收的禾。”\n\n鬼消失的方式不是被超度。是有人终于把欠的课补上。");
		case ENightEnding::HalfPage:
			return TEXT("你从正门离开的时候，天已经灰了。你不是空着手：你记得一些句子，一些灯，一个适合做开场的河。论文在开题报告里标题暂定《民间叙事中的校园传说》。导师这回批了两个字：可以。\n\n发表的那天，林秋禾的名字被编辑改成了“林秋和”。编辑说读起来更顺，也更像一个化名。你看着那个“和”，觉得它确实更像故事。你把光标放在“和”上面，停了很久，然后去改了摘要里的一个逗号。\n\n有读者留言说害怕。你回复了一个微笑。夜里你梦见签到簿。你想把那个错字改回来，笔在纸上只划出一声“可以”。你醒过来，发现自己记住了阅读量，没有记住她母亲的名字。你从来没有问过。\n\n半页不是没写完。是你觉得够用了。");
		case ENightEnding::Nameless:
			if (bFromFear)
			{
				return TEXT("名字是你一个一个捡回来的，又一个一个掉在楼道里。最后掉的是你自己的。林秋禾没有追上来。她只是把你捡过的纸按顺序叠好，很轻地说：你看，只记得害怕的人，也会变成名册上被烧去的那一角。\n\n你在天亮时坐在废墟边，还能为别人讲一个很恐怖的故事，讲到一半一定会忘词。听的人说没关系，恐怖故事本来就不需要名字。你笑了。那是你今天唯一还做得出的表情。你不知道自己在笑什么。\n\n你只知道从今往后，所有被你讲过的人，都会在句子里慢慢失去笔画。包括你。\n\n害怕不是结局。害怕只是一种很有效的橡皮擦。");
			}
			return TEXT("你顺着门厅离开。除夕的风很干。你在拆迁告示前站住，想给导师发一条“这里什么都没有”。发送失败。不是没有信号，是收件人那一栏空着，你的署名那一栏也空着。\n\n工地的人第二天把你从台阶上叫醒，问你叫什么，好写进无关人员登记表。你张开嘴，发出的声音像一枚按歪的手印。学生证还在口袋里，照片是你，名字的位置被烧成一个整齐的方洞，像专门留出来给别人填写。\n\n你走在街上，招牌都在。你一个也念不出来。不是天黑，是字从你身上开始撤回去了。你这才明白：不被记录的人，先失去的不是生命，是被人叫一声的可能。\n\n你站在路口，等一个愿意把你的名字写对的人。车流很长。没有人停车。对这座城来说，一个念不出自己名字的人，甚至构不成事故。");
		default:
			return TEXT("");
		}
	}

